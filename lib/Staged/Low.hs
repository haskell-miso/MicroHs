-- First order low code, the result of reflect.

-- Variables are named uniquely in a program; every binder carries its type.
data LowTerm
  = LVar String LowTy                        -- a variable, with its type
  | LLit LowLit LowTy
  | LPrim String LowTy                       -- a primitive of the runtime system (e.g. "+" on Int), with its type
  | LForeign String String LowTy             -- a foreign (C) function: Haskell name, C name, type
  | LApp LowTerm [LowTerm]                   -- a saturated call of a variable, primitive, or foreign function
  | LLam [(String, LowTy)] LowTerm           -- a function; only as the right hand side of a let, or the program
  | LLet String LowTy LowTerm LowTerm        -- let x :: t = e in b  (e is evaluated first, unless it is a function)
  | LLetRec [(String, LowTy, LowTerm)] LowTerm   -- recursive functions
  | LCase LowTerm [LowCon] [(LowCon, [(String, LowTy)], LowTerm)] (Maybe LowTerm)
                                             -- scrutinee, all constructors of its type, alternatives, default
  | LCon LowCon LowTy [LowTerm]              -- a saturated constructor application; the type of the value
  | LFail String                             -- a failed pattern match or error

data LowProg = LowProg {
  progType  :: LowTy,                        -- the type of the program
  progFree  :: [(String, LowTy)],            -- the free (object level) variables
  progDecls :: [LowDecl],                    -- the data types used
  progBody  :: LowTerm
  }

-- The type of a term.
typeOf :: LowTerm -> LowTy
typeOf at =
  case at of
    LVar _ t -> t
    LLit _ t -> t
    LPrim _ t -> t
    LForeign _ _ t -> t
    LApp f as -> applyTy (typeOf f) (length as)
    LLam xs b -> mkFun (map snd xs) (typeOf b)
    LLet _ _ _ b -> typeOf b
    LLetRec _ b -> typeOf b
    LCase _ _ ((_, _, b) : _) _ -> typeOf b
    LCase _ _ [] (Just d) -> typeOf d
    LCase _ _ [] Nothing -> TOther "empty case"
    LCon _ t _ -> t
    LFail _ -> TOther "fail"

-- The number of arguments of a function type.
arity :: LowTy -> Int
arity (TFun as _) = length as
arity _ = 0

resultType :: LowTy -> LowTy
resultType = lowFunResult

applyTy :: LowTy -> Int -> LowTy
applyTy t 0 = t
applyTy (TFun as r) n
  | n < length as = TFun (drop n as) r
  | n == length as = r
  | otherwise = applyTy r (n - length as)
applyTy _ _ = TOther "application of a non-function"

mkFun :: [LowTy] -> LowTy -> LowTy
mkFun [] r = r
mkFun as (TFun bs r) = TFun (as ++ bs) r
mkFun as r = TFun as r

-- The field types of a constructor of a data type (with the type arguments substituted).
conFieldTypes :: LowTy -> LowCon -> [LowTy]
conFieldTypes (TData _ args decl) con =
  case [ conDeclFields c | c <- declCons decl, conDeclTag c == conTag con ] of
    fs : _ -> map (substParams args) fs
    [] -> []
conFieldTypes _ _ = []

substParams :: [LowTy] -> LowTy -> LowTy
substParams args t =
  case t of
    TParam i | i < length args -> args !! i
    TFun as r -> TFun (map (substParams args) as) (substParams args r)
    TData n as d -> TData n (map (substParams args) as) d
    _ -> t

-- The name without the module qualifier.
baseName :: String -> String
baseName s =
  case break (== '.') s of
    (m, '.' : r) | not (null m) && all (\ c -> c /= '(' && c /= '[') m && not (null r) -> baseName r
    _ -> s

-- The free variables of a term.
freeVars :: LowTerm -> [(String, LowTy)]
freeVars = nub . go []
  where
    go bound at =
      case at of
        LVar x t | x `elem` bound -> []
                 | otherwise -> [(x, t)]
        LLit _ _ -> []
        LPrim _ _ -> []
        LForeign _ _ _ -> []
        LApp f as -> concatMap (go bound) (f : as)
        LLam xs b -> go (map fst xs ++ bound) b
        LLet x _ e b -> go bound e ++ go (x : bound) b
        LLetRec bs b -> let bound' = [ x | (x, _, _) <- bs ] ++ bound
                        in concatMap (\ (_, _, e) -> go bound' e) bs ++ go bound' b
        LCase s _ alts d -> go bound s ++ concatMap (\ (_, xs, b) -> go (map fst xs ++ bound) b) alts ++ maybe [] (go bound) d
        LCon _ _ as -> concatMap (go bound) as
        LFail _ -> []

