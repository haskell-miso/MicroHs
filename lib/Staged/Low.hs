-- Compile time values as low code.

lowInt :: Int -> Low Int
lowInt i = toLow (HLit (LitInt i) TInt)

lowWord :: Word -> Low Word
lowWord w = toLow (HLit (LitInt (fromIntegral w)) TWord)

lowDouble :: Double -> Low Double
lowDouble d = toLow (HLit (LitDouble d) TDouble)

lowFloat :: Float -> Low Float
lowFloat f = toLow (HLit (LitFloat f) TFloat)

lowChar :: Char -> Low Char
lowChar c = toLow (HLit (LitChar c) TChar)

lowString :: String -> Low String
lowString s = toLow (HLit (LitString s) (lowTyOf s))

lowBool :: Bool -> Low Bool
lowBool True = [| True |]
lowBool False = [| False |]
