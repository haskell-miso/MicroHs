-- Reflection: read back the HOAS representation as first order terms.

-- A small state monad: the names in use (with a counter), and the free variables.
newtype R a = R (RS -> (a, RS))
data RS = RS [(String, Int)] [(Int, String, String, LowTy)]

unR :: R a -> RS -> (a, RS)
unR (R f) = f

instance Functor R where
  fmap f (R g) = R $ \ s -> case g s of (a, s') -> (f a, s')
instance Applicative R where
  pure a = R $ \ s -> (a, s)
  R f <*> R a = R $ \ s -> case f s of (g, s') -> case a s' of (b, s'') -> (g b, s'')
instance Monad R where
  R g >>= f = R $ \ s -> case g s of (a, s') -> unR (f a) s'

-- A fresh variable name, based on the name in the source.
fresh :: String -> R String
fresh s = R $ \ (RS ns fs) ->
  let base = case dropWhile (== '$') s of
               "" -> "v"
               b@(c : _) | c >= 'a' && c <= 'z' || c == '_' -> b
                         | otherwise -> "v"
      n = maybe 0 id (lookup base ns)
      ns' = (base, n + 1) : filter ((/= base) . fst) ns
      name = if n == 0 then base else base ++ show n
  in  (name, RS ns' fs)

-- The name of a free (object level) variable.
freeVar :: Int -> String -> LowTy -> R String
freeVar l x t = R $ \ st@(RS _ fs) ->
  case [ n | (l', x', n, _) <- fs, l' == l, x' == x ] of
    n : _ -> (n, st)
    [] -> case unR (fresh x) st of
            (n, RS ns fs') -> (n, RS ns (fs' ++ [(l, x, n, t)]))

-- The level of the variables bound by the read back; the others are free variables.
boundLevel :: Int
boundLevel = -1

readBack :: LowExp -> R LowTerm
readBack ae =
  case ae of
    HVar l x t | l == boundLevel -> return (LVar x t)
               | otherwise -> do { n <- freeVar l x t; return (LVar n t) }
    HLam x t f -> do
      x' <- fresh x
      b <- readBack (f (HVar boundLevel x' t))
      return (LLam [(x', t)] b)
    HApp f as -> LApp <$> readBack f <*> mapM readBack as
    HLet x mt e f -> do
      e' <- readBack e
      let t = maybe (typeOf e') id mt
      x' <- fresh x
      b <- readBack (f (HVar boundLevel x' t))
      return (LLet x' t e' b)
    HLetRec xts f -> do
      xs <- mapM (fresh . fst) xts
      let ts = map snd xts
          (es, b) = f (zipWith (HVar boundLevel) xs ts)
      es' <- mapM readBack es
      b' <- readBack b
      return (LLetRec (zip3 xs ts es') b')
    HCase s cons alts d -> do
      s' <- readBack s
      let st = typeOf s'
          alt (LowAlt con names f) = do
            xs <- mapM fresh names
            let ts = conFieldTypes st con
                ts' = ts ++ replicate (length xs - length ts) (TOther "unknown field type")
            b <- readBack (f (zipWith (HVar boundLevel) xs ts'))
            return (con, zip xs ts', b)
      alts' <- mapM alt alts
      d' <- maybe (return Nothing) (fmap Just . readBack) d
      return (LCase s' cons alts' d')
    HCon c t as -> LCon c t <$> mapM readBack as
    HLit l t -> return (LLit l t)
    HPrim p t -> return (LPrim p t)
    HForeign h c t -> return (LForeign h c t)
    HFail m -> return (LFail m)

-- Call saturation: afterwards every call (LApp) has as many arguments as the
-- function type has, every constructor application is saturated, and functions
-- (LLam) only occur as the right hand side of lets, or as the whole program.
-- (Section 2.2 of the CFTT paper.)
saturate :: LowTerm -> R LowTerm
saturate at =
  case at of
    LApp f as -> do
      f' <- saturate f
      as' <- mapM saturate as
      satApp f' as'
    LLam xs b -> mergeLam xs <$> saturate b
    LLet x t e b -> do
      e' <- saturate e >>= etaTo t
      LLet x t e' <$> saturate b
    LLetRec bs b -> do
      bs' <- mapM (\ (x, t, e) -> do { e' <- saturate e >>= etaTo t; return (x, t, e') }) bs
      LLetRec bs' <$> saturate b
    LCase s cons alts d -> do
      s' <- saturate s
      alts' <- mapM (\ (c, xs, b) -> do { b' <- saturate b; return (c, xs, b') }) alts
      d' <- maybe (return Nothing) (fmap Just . saturate) d
      return (LCase s' cons alts' d')
    LCon c t as -> do
      as' <- mapM saturate as
      let n = conArity c
      if length as' < n then
        etaCon c t as'
       else
        return (LCon c (applyTy t (length as')) as')
    _ -> return at

mergeLam :: [(String, LowTy)] -> LowTerm -> LowTerm
mergeLam xs (LLam ys b) = LLam (xs ++ ys) b
mergeLam xs b = LLam xs b

-- Apply a (saturated) term to (saturated) arguments.
satApp :: LowTerm -> [LowTerm] -> R LowTerm
satApp f [] = return f
satApp f as =
  case f of
    LLam xs b ->
      -- beta: bind the arguments with lets
      let n = min (length xs) (length as)
          binds = zip (take n xs) (take n as)
          rest = drop n xs
          rest' = drop n as
      in  do b' <- if null rest then satApp b rest' else return (LLam rest b)
             return (foldr (\ ((x, t), e) r -> LLet x t e r) b' binds)
    LLet x t e b -> LLet x t e <$> satApp b as
    LLetRec bs b -> LLetRec bs <$> satApp b as
    LCase s cons alts d ->
      -- push the arguments into the alternatives; non-trivial arguments are let bound first
      bindArgs as $ \ vs -> do
        alts' <- mapM (\ (c, xs, b) -> do { b' <- satApp b vs; return (c, xs, b') }) alts
        d' <- maybe (return Nothing) (fmap Just . (`satApp` vs)) d
        return (LCase s cons alts' d')
    LCon c t as' -> saturate (LCon c t (as' ++ as))
    _ -> do
      let n = arity (typeOf f)
      if length as < n then
        etaApp f as
       else if length as == n then
        return (LApp f as)
       else
        satApp (LApp f (take n as)) (drop n as)

bindArgs :: [LowTerm] -> ([LowTerm] -> R LowTerm) -> R LowTerm
bindArgs as k = go [] as
  where
    go acc [] = k (reverse acc)
    go acc (a : rest) =
      case a of
        LVar _ _ -> go (a : acc) rest
        LLit _ _ -> go (a : acc) rest
        _ -> do
          x <- fresh "a"
          let t = typeOf a
          b <- go (LVar x t : acc) rest
          return (LLet x t a b)

-- Eta expand a partial application to a function.
etaApp :: LowTerm -> [LowTerm] -> R LowTerm
etaApp f as =
  case applyTy (typeOf f) (length as) of
    TFun ps _ -> do
      vs <- mapM (const (fresh "x")) ps
      let xs = zip vs ps
      return (LLam xs (LApp f (as ++ map (\ (v, t) -> LVar v t) xs)))
    _ -> return (LApp f as)

etaCon :: LowCon -> LowTy -> [LowTerm] -> R LowTerm
etaCon c t as =
  case applyTy t (length as) of
    TFun ps r -> do
      vs <- mapM (const (fresh "x")) ps
      let xs = zip vs ps
      return (LLam xs (LCon c r (as ++ map (\ (v, t') -> LVar v t') xs)))
    _ -> return (LCon c t as)

-- Make a term of function type a lambda.
etaTo :: LowTy -> LowTerm -> R LowTerm
etaTo t e =
  case (t, e) of
    (TFun _ _, LLam _ _) -> return e
    (TFun ps _, _) -> do
      vs <- mapM (const (fresh "x")) ps
      let xs = zip vs ps
      b <- satApp e (map (\ (v, t') -> LVar v t') xs)
      return (mergeLam xs b)
    _ -> return e

-- The declarations of the data types used in a term (and in the types).
collectDecls :: LowTerm -> [LowDecl]
collectDecls t0 = reverse (go [] t0)
  where
    go acc at =
      case at of
        LVar _ t -> ty acc t
        LLit _ t -> ty acc t
        LPrim _ t -> ty acc t
        LForeign _ _ t -> ty acc t
        LApp f as -> foldl go (go acc f) as
        LLam xs b -> go (foldl ty acc (map snd xs)) b
        LLet _ t e b -> go (go (ty acc t) e) b
        LLetRec bs b -> go (foldl (\ a (_, t, e) -> go (ty a t) e) acc bs) b
        LCase s _ alts d -> let acc1 = go acc s
                                acc2 = foldl (\ a (_, xs, b) -> go (foldl ty a (map snd xs)) b) acc1 alts
                            in maybe acc2 (go acc2) d
        LCon _ t as -> foldl go (ty acc t) as
        LFail _ -> acc
    ty acc t =
      case t of
        TFun as r -> foldl ty (ty acc r) as
        TData n as d | n `elem` map declName acc -> foldl ty acc as
                     | otherwise -> foldl ty (foldl ty (d : acc) (concatMap conDeclFields (declCons d))) as
        _ -> acc

-- Reflect low code into a first order program.
reflect :: forall a . Low a -> LowProg
reflect l =
  let act = do
        b <- readBack (fromLow l)
        b' <- saturate b >>= etaTo (typeOf b)
        return b'
      (body, RS _ fs) = unR act (RS [] [])
  in  LowProg { progType = typeOf body
              , progFree = [ (n, t) | (_, _, n, t) <- fs ]
              , progDecls = collectDecls body
              , progBody = body }

