-- Closure-free two-level type theory (CFTT, Kovacs ICFP 2024): low code.
--
--   Low a       the meta level type of closure free object code of type a
--
-- Quotations [| e |] and splices ~e are shared with Code (see Staged); a
-- quotation is Low when its type is (Low t).  Low code is a first order,
-- strict, monomorphic subset of Haskell:
--
--  * values have value types: the primitive numeric and character types, and
--    data types whose fields are value types (no functions in data);
--  * functions are first order: the arguments are values (no higher order
--    functions), so no closures are ever needed at run time;
--  * let bound values and function arguments are evaluated (call by value);
--  * class methods are only available at known instances where they are
--    primitives (e.g. + on Int), there is no overloading; other global
--    functions are not available, only constructors and local definitions.
--
-- Low code is generated by ordinary (meta level) Haskell code, which can use
-- all of Haskell; it is in the generated code that functions are first order.
-- Spliced into object code, low code runs as ordinary MicroHs code.
-- With reflect, the generated code is available as a first order syntax tree
-- (LowProg), with the type of every binder, for user written code generators
-- (see Staged.Low.C and Staged.Low.JS).
--
-- A type variable in low code stands for a value type: a generator that is
-- polymorphic in a type that is used in low code needs a (LowRep a) constraint,
-- which the compiler solves for every concrete type.
module Staged.Low(
  Low, LowRep,
  LowTy(..), LowDecl(..), LowConDecl(..), LowCon(..), LowLit(..),
  LowTerm(..), LowProg(..),
  reflect, typeOf, arity, resultType, conFieldTypes, baseName, freeVars,
  lowPretty, lowPrettyTerm,
  Gen(..), runGen, gen, genRec, genLet,
  lowInt, lowWord, lowDouble, lowFloat, lowChar, lowString, lowBool,
  ) where
import Prelude
import Data.List(nub, intercalate)
import Staged.Low.Internal

