-- The code generation monad (let insertion), as in Staged, for low code.

newtype Gen a = Gen (forall r . (a -> Low r) -> Low r)

unGen :: forall a r . Gen a -> (a -> Low r) -> Low r
unGen (Gen f) = f

instance Functor Gen where
  fmap f (Gen g) = Gen $ \ k -> g (k . f)

instance Applicative Gen where
  pure a = Gen $ \ k -> k a
  Gen f <*> Gen a = Gen $ \ k -> f (\ g -> a (k . g))

instance Monad Gen where
  Gen g >>= f = Gen $ \ k -> g (\ a -> unGen (f a) k)

runGen :: forall a . Gen (Low a) -> Low a
runGen (Gen f) = f id

-- Bind the code to a variable, so it is evaluated once, and return (code for) the variable.
gen :: forall a . LowRep a => Low a -> Gen (Low a)
gen c = Gen $ \ k -> [| let x = ~c in ~(k [| x |]) |]

-- A recursive definition (a function): the generator gets (code for) the variable being defined.
genRec :: forall a . LowRep a => (Low a -> Low a) -> Gen (Low a)
genRec f = Gen $ \ k -> [| let x = ~(f [| x |]) in ~(k [| x |]) |]

genLet :: forall a b . LowRep a => Low a -> (Low a -> Low b) -> Low b
genLet c f = [| let x = ~c in ~(f [| x |]) |]

-----------------------------------------------------------------------
-- Compile time values as low code.

lowInt :: Int -> Low Int
lowInt i = toLow (HLit (LitInt i) TInt)

lowWord :: Word -> Low Word
lowWord w = toLow (HLit (LitInt (fromIntegral w)) TWord)

lowDouble :: Double -> Low Double
lowDouble d = toLow (HLit (LitDouble d) TDouble)

lowFloat :: Float -> Low Float
lowFloat f = toLow (HLit (LitFloat f) TFloat)

lowChar :: Char -> Low Char
lowChar c = toLow (HLit (LitChar c) TChar)

lowString :: String -> Low String
lowString s = toLow (HLit (LitString s) (lowTyOf s))

lowBool :: Bool -> Low Bool
lowBool True = [| True |]
lowBool False = [| False |]
